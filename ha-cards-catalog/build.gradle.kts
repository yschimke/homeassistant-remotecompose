// `:ha-cards-catalog` — the `ha-cards` UI-builder catalog: Home Assistant cards in Remote Compose,
// for the white-labelled builder on ha.coo.ee.
//
// A design system of its own beside the sticker sheet `:previews` publishes as
// `homeassistant-remotecompose`, and beside the typed catalog `:ui-builder-catalog`. That sheet is
// a gallery of whole converted cards; this module is a builder palette: every sticker records one
// call a design can place, with arguments the record-driven Remote Compose emitter can write.
//
// - **HA card components** (`HaCardComponents.kt`): scalar `@RemoteComposable` wrappers over the
//   Tier-1 `RemoteHa*` components in `:rc-components`, whose data classes a design cannot author.
// - **Remote Material 3** (`RemoteText`, `RemoteButton`, `RemoteSwitchButton`, `RemoteCard`):
//   re-declared under the `ha-cards/` prefix, because a catalog cannot extend `remote-m3`.
//
// Three design targets share the one palette — a dashboard card, a Wear widget and a phone launcher
// widget — and are told apart by a design's root (see ui-builder.policy.json). The starting
// templates under ui-builder/designs/ are generated by `:design-server`'s HaCardsTemplatesTest from
// the same CardSchema / UiBuilderSeed the design server seeds UI Builder with.
