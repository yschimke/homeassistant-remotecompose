def terrazzo(seed, palette, count, box, rmin, rmax):
  """Angular stone flakes scattered over [box], none overlapping."""
  rnd = random.Random(seed)
  placed, chips = [], []
  for _ in range(count * 60):
    if len(chips) >= count:
      break
    r = rnd.uniform(rmin, rmax)
    cx, cy = rnd.uniform(box[0], box[2]), rnd.uniform(box[1], box[3])
    if any(math.hypot(cx - px, cy - py) < r + pr + 0.9 for px, py, pr in placed):
      continue
    placed.append((cx, cy, r))
    sides = rnd.choice((3, 4, 4, 5, 5, 6))
    rot = rnd.uniform(0, 360)
    stretch = rnd.uniform(0.55, 1.0)
    ca, sa = math.cos(math.radians(rot)), math.sin(math.radians(rot))
    pts = []
    for i in range(sides):
      a = math.radians(i * 360 / sides + rnd.uniform(-22, 22))
      rr = r * rnd.uniform(0.65, 1.0)
      dx, dy = rr * math.cos(a), rr * math.sin(a) * stretch
      pts.append((cx + dx * ca - dy * sa, cy + dx * sa + dy * ca))
    color, alpha = palette[rnd.randrange(len(palette))]
    chips.append(P(poly(*pts), fill=color, alpha=alpha))
  return chips


