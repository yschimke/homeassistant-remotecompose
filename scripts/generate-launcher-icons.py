def argb(color, alpha):
  return "#" + f"{round(alpha * 255):02X}" + color[1:]


def vector_xml(paths, scale=1.0):
  out = [
    '<?xml version="1.0" encoding="utf-8"?>',
    HEADER,
    '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
    '    xmlns:aapt="http://schemas.android.com/aapt"',
    '    android:width="108dp"',
    '    android:height="108dp"',
    '    android:viewportWidth="108"',
    '    android:viewportHeight="108">',
  ]
  for p in paths:
    attrs = [f'android:pathData="{p.d}"']
    gradient = None
    if isinstance(p.fill, G):
      g = p.fill
      geo = (f'android:type="radial" android:centerX="{f(g.x0)}" android:centerY="{f(g.y0)}" '
             f'android:gradientRadius="{f(g.r)}"' if g.radial else
             f'android:type="linear" android:startX="{f(g.x0)}" android:startY="{f(g.y0)}" '
             f'android:endX="{f(g.x1)}" android:endY="{f(g.y1)}"')
      items = "".join(f'\n                <item android:offset="{f(o)}" android:color="{argb(c, a)}" />'
                      for o, c, a in g.stops)
      gradient = ('\n        <aapt:attr name="android:fillColor">'
                  f'\n            <gradient {geo}>{items}\n            </gradient>'
                  '\n        </aapt:attr>')
    elif p.fill:
      attrs.append(f'android:fillColor="{p.fill}"')
    if p.fill:
      if p.alpha != 1:
        attrs.append(f'android:fillAlpha="{f(p.alpha)}"')
      if p.evenodd:
        attrs.append('android:fillType="evenOdd"')
    if p.stroke:
      attrs.append(f'android:strokeColor="{p.stroke}"')
      attrs.append(f'android:strokeWidth="{f(p.sw)}"')
      attrs.append('android:strokeLineJoin="round"')
      attrs.append(f'android:strokeLineCap="{p.cap}"')
      if p.alpha != 1:
        attrs.append(f'android:strokeAlpha="{f(p.alpha)}"')
    head = "    <path\n        " + "\n        ".join(attrs)
    out.append(head + (">" + gradient + "\n    </path>" if gradient else " />"))
  if scale != 1:
    body = "\n".join("    " + l for l in "\n".join(out[8:]).split("\n"))
    out = out[:8] + [f'    <group android:pivotX="54" android:pivotY="54" android:scaleX="{f(scale)}" '
                     f'android:scaleY="{f(scale)}">', body, "    </group>"]
  out.append("</vector>")
  return "\n".join(out) + "\n"


_ids = iter(range(1, 1 << 30))


def svg_paths(paths):
  out = []
  for p in paths:
    fill = p.fill or "none"
    if isinstance(p.fill, G):
      g, gid = p.fill, f"g{next(_ids)}"
      stops = "".join(f'<stop offset="{o}" stop-color="{c}" stop-opacity="{a}"/>' for o, c, a in g.stops)
      geo = (f'cx="{g.x0}" cy="{g.y0}" r="{g.r}"' if g.radial else
             f'x1="{g.x0}" y1="{g.y0}" x2="{g.x1}" y2="{g.y1}"')
      tag = "radialGradient" if g.radial else "linearGradient"
      out.append(f'<defs><{tag} id="{gid}" gradientUnits="userSpaceOnUse" {geo}>{stops}</{tag}></defs>')
      fill = f"url(#{gid})"
    a = [f'd="{p.d}"', f'fill="{fill}"']
    if p.alpha != 1:
      a.append(f'opacity="{f(p.alpha)}"')
    if p.evenodd:
      a.append('fill-rule="evenodd"')
    if p.stroke:
      a += [f'stroke="{p.stroke}"', f'stroke-width="{f(p.sw)}"', 'stroke-linejoin="round"',
            f'stroke-linecap="{p.cap}"']
    out.append(f"<path {' '.join(a)}/>")
  return "".join(out)


# Launcher masks over the visible 72dp (18..90) of the 108dp canvas.
MASKS = {
  "circle": '<circle cx="54" cy="54" r="36"/>',
  "squircle": '<path d="M54,18 C84,18 90,24 90,54 C90,84 84,90 54,90 C24,90 18,84 18,54 C18,24 24,18 54,18 Z"/>',
  "rounded square": '<rect x="18" y="18" width="72" height="72" rx="13"/>',
  "teardrop": '<path d="M54,18 A36,36 0 0,1 90,54 V90 H54 A36,36 0 0,1 54,18 Z"/>',
}


def svg(icon, mask="circle", size=120):
  s = icon.scale
  body = (svg_paths(icon.background) +
          f'<g transform="translate(54 54) scale({s}) translate(-54 -54)">{svg_paths(icon.foreground)}</g>')
  if mask == "full":
    return (
      f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" width="{size}" height="{size}">'
      f'{body}<rect x="18" y="18" width="72" height="72" fill="none" stroke="#fff" stroke-width="0.6" stroke-dasharray="2 2"/>'
      f'<circle cx="54" cy="54" r="33" fill="none" stroke="#f0f" stroke-width="0.6" stroke-dasharray="2 2"/></svg>'
    )
  cid = f"m{next(_ids)}"  # unique: the sheet inlines every SVG
  return (
    f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="18 18 72 72" width="{size}" height="{size}">'
    f'<clipPath id="{cid}">{MASKS[mask]}</clipPath><g clip-path="url(#{cid})">{body}</g></svg>'
  )


def adaptive_xml(bg, fg, mono=None):
  lines = [
    '<?xml version="1.0" encoding="utf-8"?>',
    HEADER,
    '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">',
    f'    <background android:drawable="@drawable/{bg}" />',
    f'    <foreground android:drawable="@drawable/{fg}" />',
  ]
  if mono:
    lines.append(f'    <monochrome android:drawable="@drawable/{mono}" />')
  lines.append("</adaptive-icon>")
  return "\n".join(lines) + "\n"


def write(path, text):
  os.makedirs(os.path.dirname(path), exist_ok=True)
  with open(path, "w") as fh:
    fh.write(text)


def main():
  ap = argparse.ArgumentParser()
  ap.add_argument("--svg", help="also write SVG previews and a mask contact sheet to this directory")
  args = ap.parse_args()

  light, night = default_icon(False), default_icon(True)
  d = DEFAULT_RES
  # The terrazzo ground is a drawable; its base colour stays a colour resource too, for the Play
  # graphics previews.
  write(f"{d}/drawable/ic_launcher_background.xml", vector_xml(light.background))
  write(f"{d}/drawable-night/ic_launcher_background.xml", vector_xml(night.background))
  for qualifier, icon in (("values", light), ("values-night", night)):
    write(f"{d}/{qualifier}/ic_launcher_background.xml",
          '<?xml version="1.0" encoding="utf-8"?>\n' + HEADER + "\n<resources>\n"
          f'    <color name="ic_launcher_background">{icon.background[0].fill}</color>\n'
          "</resources>\n")
  write(f"{d}/drawable/ic_launcher_foreground.xml", vector_xml(light.foreground))
  write(f"{d}/drawable-night/ic_launcher_foreground.xml", vector_xml(night.foreground))
  write(f"{d}/drawable/ic_launcher_monochrome.xml", vector_xml(light.monochrome))
  for name in ("ic_launcher", "ic_launcher_round"):
    write(f"{d}/mipmap-anydpi-v26/{name}.xml",
          adaptive_xml("ic_launcher_background", "ic_launcher_foreground", "ic_launcher_monochrome"))

  icons = [light, night]
  for make in DESIGNS:
    icon = make()
    icons.append(icon)
    k = icon.key
    write(f"{DESIGN_RES}/drawable/ic_launcher_{k}_background.xml", vector_xml(icon.background))
    write(f"{DESIGN_RES}/drawable/ic_launcher_{k}_foreground.xml",
          vector_xml(icon.foreground, icon.scale))
    write(f"{DESIGN_RES}/mipmap-anydpi-v26/ic_launcher_{k}.xml",
          adaptive_xml(f"ic_launcher_{k}_background", f"ic_launcher_{k}_foreground"))

  if args.svg:
    os.makedirs(args.svg, exist_ok=True)
    mono = Icon("themed", [full("#D9E2FF")],
                [P(p.d, fill="#1B2A55" if p.fill else None, stroke="#1B2A55" if p.stroke else None,
                   sw=p.sw, alpha=p.alpha) for p in light.monochrome])
    cols = list(MASKS) + ["full"]
    head = "".join(f"<th>{c}</th>" for c in ["", *cols[:-1], "full layer + safe zone"])
    rows = []
    for icon in icons + [mono]:
      write(f"{args.svg}/{icon.key}.svg", svg(icon))
      cells = "".join(f"<td>{svg(icon, m, 96)}</td>" for m in cols)
      rows.append(f"<tr><th>{icon.key}</th>{cells}</tr>")
    write(f"{args.svg}/sheet.html",
          '<html><body style="margin:0;padding:12px;background:#6b6b6b;font:13px sans-serif;color:#fff">'
          '<table style="border-spacing:14px 8px"><tr>' + head + "</tr>" + "".join(rows)
          + "</table></body></html>")


if __name__ == "__main__":
  main()
