@dataclass
class G:
  """A gradient fill in viewport units: linear from (x0, y0) to (x1, y1), or radial at (x0, y0)
  with radius r. Stops are (offset, #RRGGBB, alpha)."""

  stops: list
  x0: float = 0
  y0: float = 0
  x1: float = 0
  y1: float = 108
  r: float = 0

  @property
  def radial(self):
    return self.r > 0


@dataclass
class P:
  """One vector path. Fill is #RRGGBB or a [G]; alpha applies to fill and stroke alike."""

  d: str
  fill: "str | G | None" = None
  stroke: str | None = None
  sw: float = 0
  alpha: float = 1.0
  evenodd: bool = False
  cap: str = "round"


@dataclass
class Icon:
  key: str
  background: list = field(default_factory=list)
  foreground: list = field(default_factory=list)
  monochrome: list | None = None
  scale: float = 1.0  # shrinks the foreground about the centre, into the 66dp safe circle


def lin(x0, y0, x1, y1, *stops):
  return G(list(stops), x0, y0, x1, y1)


def rad(cx, cy, r, *stops):
  return G(list(stops), cx, cy, r=r)


# --- geometry ------------------------------------------------------------------------------------


def f(v):
  return f"{v:.2f}".rstrip("0").rstrip(".")


def circle(cx, cy, r):
  return f"M{f(cx - r)},{f(cy)}a{f(r)},{f(r)} 0 1,0 {f(2 * r)},0a{f(r)},{f(r)} 0 1,0 {f(-2 * r)},0Z"


def rect(x, y, w, h, r=0):
  if r == 0:
    return f"M{f(x)},{f(y)}h{f(w)}v{f(h)}h{f(-w)}Z"
  r = min(r, w / 2, h / 2)
  return (
    f"M{f(x + r)},{f(y)}h{f(w - 2 * r)}a{f(r)},{f(r)} 0 0,1 {f(r)},{f(r)}"
    f"v{f(h - 2 * r)}a{f(r)},{f(r)} 0 0,1 {f(-r)},{f(r)}h{f(-(w - 2 * r))}"
    f"a{f(r)},{f(r)} 0 0,1 {f(-r)},{f(-r)}v{f(-(h - 2 * r))}a{f(r)},{f(r)} 0 0,1 {f(r)},{f(-r)}Z"
  )


def poly(*pts, close=True):
  s = "M" + " L".join(f"{f(x)},{f(y)}" for x, y in pts)
  return s + ("Z" if close else "")


def line(x0, y0, x1, y1):
  return f"M{f(x0)},{f(y0)}L{f(x1)},{f(y1)}"


def polar(cx, cy, r, a):
  """Point at angle [a] degrees clockwise from 12 o'clock."""
  t = math.radians(a - 90)
  return cx + r * math.cos(t), cy + r * math.sin(t)


def arc(cx, cy, r, a0, a1):
  """Open arc from a0 to a1, clockwise, degrees from 12 o'clock."""
  x0, y0 = polar(cx, cy, r, a0)
  x1, y1 = polar(cx, cy, r, a1)
  large = 1 if (a1 - a0) % 360 > 180 else 0
  return f"M{f(x0)},{f(y0)}A{f(r)},{f(r)} 0 {large},1 {f(x1)},{f(y1)}"


def ellipse(cx, cy, rx, ry):
  return f"M{f(cx - rx)},{f(cy)}a{f(rx)},{f(ry)} 0 1,0 {f(2 * rx)},0a{f(rx)},{f(ry)} 0 1,0 {f(-2 * rx)},0Z"


def full(fill):
  return P(rect(0, 0, 108, 108), fill=fill)


SEGMENTS = {
  "0": "abcdef", "1": "bc", "2": "abged", "3": "abgcd", "4": "fgbc", "5": "afgcd",
  "6": "afgedc", "7": "abc", "8": "abcdefg", "9": "abcdfg", "-": "g",
}


def seven_segment(x, y, w, h, t, lit, skew=0.1, gap=0.7):
  """The seven bevelled segments of a digit box, as (segment, path, lit) triples, sheared by
  [skew]. [lit] is a digit or a string of segment letters."""
  on = SEGMENTS.get(lit, lit)

  def sh(px, py):
    return px + (y + h - py) * skew, py

  def hseg(x0, x1, yc):
    return poly(*(sh(*p) for p in [(x0, yc), (x0 + t / 2, yc - t / 2), (x1 - t / 2, yc - t / 2),
                                   (x1, yc), (x1 - t / 2, yc + t / 2), (x0 + t / 2, yc + t / 2)]))

  def vseg(xc, y0, y1):
    return poly(*(sh(*p) for p in [(xc, y0), (xc + t / 2, y0 + t / 2), (xc + t / 2, y1 - t / 2),
                                   (xc, y1), (xc - t / 2, y1 - t / 2), (xc - t / 2, y0 + t / 2)]))

  m = h / 2
  segs = {
    "a": hseg(x + gap, x + w - gap, y),
    "b": vseg(x + w, y + gap, y + m - gap),
    "c": vseg(x + w, y + m + gap, y + h - gap),
    "d": hseg(x + gap, x + w - gap, y + h),
    "e": vseg(x, y + m + gap, y + h - gap),
    "f": vseg(x, y + gap, y + m - gap),
    "g": hseg(x + gap, x + w - gap, y + m),
  }
  return [(k, d, k in on) for k, d in segs.items()]


