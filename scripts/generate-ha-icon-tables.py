#!/usr/bin/env python3
"""
Generate Home Assistant's icon tables for rc-converter.

Writes one Kotlin file (checked in, so builds stay offline and reproducible):

* rc-converter/src/commonMain/kotlin/ee/schimke/ha/rc/icons/HaIconTables.kt
    Home Assistant's default entity icons: core's `entity_component` icon tables (per domain
    and device class, with their state and range variants) and the frontend's domain
    fallbacks. `HaIconMap` resolves entities through them.

The glyphs themselves come from the whole MDI catalog in `io.github.timoptr:mdi-icons`
(`:rc-mdi-icons`); this script checks every icon the tables and the frontend's state-icon special
cases name exists in the pinned MDI release, so keep MDI_VERSION in step with the library's. Every
source is pinned below; bump a pin, re-run, and review the diff. Needs network access to
registry.npmjs.org and raw.githubusercontent.com.

Usage:  scripts/generate-ha-icon-tables.py [--cache-dir DIR]
Then:   build-brief ./gradlew :rc-converter:ktfmtFormatMain   (should be a no-op)

Licences: Material Design Icons are Pictogrammers' Apache-2.0 icons; Home Assistant core and
frontend are Apache-2.0. See rc-converter/icons/NOTICE.md.
"""

import argparse
import base64
import hashlib
import io
import json
import re
import sys
import tarfile
import urllib.error
import urllib.request
from pathlib import Path

MDI_VERSION = "7.4.47"  # What the pinned HA frontend ships (@mdi/js in its package.json).
HA_CORE_TAG = "2026.10.2"
HA_FRONTEND_TAG = "20260930.4"

ROOT = Path(__file__).resolve().parent.parent
MODULE = ROOT / "rc-converter"
TABLES_OUT = MODULE / "src/commonMain/kotlin/ee/schimke/ha/rc/icons/HaIconTables.kt"

# Domains with an icons.json that aren't entity platforms (helpers and integrations that own
# entities). A 404 just means the domain has no icon table at this tag.
EXTRA_DOMAINS = [
    "alert",
    "automation",
    "counter",
    "group",
    "input_boolean",
    "input_button",
    "input_datetime",
    "input_number",
    "input_select",
    "input_text",
    "person",
    "plant",
    "proximity",
    "schedule",
    "script",
    "sun",
    "timer",
    "zone",
]

# The frontend's stateIcon() special cases (src/common/entity/state_icon.ts and friends), which
# HaIconMap mirrors in code; their icons must exist in MDI_VERSION.
STATE_ICON_SPECIALS = [
    "white-balance-sunny",
    "weather-night",
    "package-up",
    "package",
    "package-down",
    "lan-connect",
    "lan-disconnect",
    "bluetooth-connect",
    "bluetooth",
    "account",
    "account-arrow-right",
    "clock",
    "calendar",
]

KT_HEADER = """\
// GENERATED by scripts/generate-ha-icon-tables.py. Do not edit; re-run the script instead.
//
// {source}
// See rc-converter/icons/NOTICE.md for the licences.
"""


def fetch(url: str, cache: Path | None) -> bytes | None:
    """GET [url]; None on 404. Cached by URL when a cache dir is given."""
    key = hashlib.sha256(url.encode()).hexdigest()[:24]
    if cache:
        hit = cache / key
        if hit.exists():
            data = hit.read_bytes()
            return None if data == b"\0404" else data
    try:
        with urllib.request.urlopen(url, timeout=60) as resp:
            data = resp.read()
    except urllib.error.HTTPError as e:
        if e.code != 404:
            raise
        data = None
    if cache:
        cache.mkdir(parents=True, exist_ok=True)
        (cache / key).write_bytes(b"\0404" if data is None else data)
    return data


def npm_tarball(package: str, version: str, cache: Path | None) -> tarfile.TarFile:
    meta = json.loads(fetch(f"https://registry.npmjs.org/{package}/{version}", cache))
    url = meta["dist"]["tarball"]
    algo, expected = meta["dist"]["integrity"].split("-", 1)
    data = fetch(url, cache)
    actual = base64.b64encode(hashlib.new(algo, data).digest()).decode()
    if actual != expected:
        sys.exit(f"{package}@{version}: tarball integrity mismatch")
    return tarfile.open(fileobj=io.BytesIO(data), mode="r:gz")


def camel(name: str) -> str:
    return "mdi" + "".join(part[:1].upper() + part[1:] for part in name.split("-"))


def load_mdi(cache: Path | None) -> dict[str, str]:
    """name -> path data for every icon in the pinned MDI release.

    Aliases in meta.json are search keywords (Home Assistant's icon picker uses them that way), not
    names an `icon:` can use, so they aren't resolved.
    """
    js = npm_tarball("@mdi/js", MDI_VERSION, cache)
    source = js.extractfile("package/mdi.js").read().decode()
    by_camel = dict(re.findall(r'export var (mdi\w+) = "([^"]+)";', source))
    svg = npm_tarball("@mdi/svg", MDI_VERSION, cache)
    meta = json.load(svg.extractfile("package/meta.json"))
    paths = {}
    for icon in meta:
        path = by_camel.get(camel(icon["name"]))
        if path is None:
            sys.exit(f"mdi:{icon['name']} has no path in @mdi/js {MDI_VERSION}")
        paths[icon["name"]] = path
    return paths


def load_core_tables(cache: Path | None) -> dict[str, dict[str, dict]]:
    """domain -> device class ('_' for the domain default) -> {default, state, range}."""
    base = f"https://raw.githubusercontent.com/home-assistant/core/{HA_CORE_TAG}/homeassistant"
    platforms_py = fetch(f"{base}/generated/entity_platforms.py", cache).decode()
    domains = sorted(set(re.findall(r'^\s+[A-Z_]+ = "([a-z_]+)"$', platforms_py, re.M)) | set(EXTRA_DOMAINS))
    tables = {}
    for domain in domains:
        raw = fetch(f"{base}/components/{domain}/icons.json", cache)
        if raw is None:
            continue
        component = json.loads(raw).get("entity_component", {})
        rules = {}
        for device_class, rule in component.items():
            if "default" not in rule:
                continue
            rules[device_class] = {
                "default": rule["default"],
                "state": rule.get("state", {}),
                "range": rule.get("range", {}),
            }
        if rules:
            tables[domain] = rules
    return tables


def load_frontend_fallbacks(cache: Path | None) -> tuple[dict[str, str], str]:
    """(domain -> icon, default icon) from the frontend's FALLBACK_DOMAIN_ICONS."""
    url = (
        f"https://raw.githubusercontent.com/home-assistant/frontend/{HA_FRONTEND_TAG}"
        "/src/data/icons.ts"
    )
    source = fetch(url, cache).decode()
    block = re.search(r"FALLBACK_DOMAIN_ICONS = \{(.*?)\};", source, re.S).group(1)
    fallbacks = dict(re.findall(r"^\s*(\w+): (mdi\w+),", block, re.M))
    default = re.search(r"DEFAULT_DOMAIN_ICON = (mdi\w+);", source).group(1)
    return fallbacks, default


def uncamel(identifier: str, names_by_camel: dict[str, str]) -> str:
    name = names_by_camel.get(identifier)
    if name is None:
        sys.exit(f"frontend icon {identifier} is not in MDI {MDI_VERSION}")
    return name


def strip(icon: str) -> str:
    if not icon.startswith("mdi:"):
        sys.exit(f"non-MDI icon in a Home Assistant table: {icon}")
    return icon[4:]



def kt_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'


def list_items(items: list[str], indent: int) -> str:
    pad = " " * indent
    return "\n".join(f"{pad}{kt_string(item)}," for item in items)



def rule_line(domain: str, device_class: str, rule: dict) -> str:
    parts = [domain, device_class, strip(rule["default"])]
    parts += [f"s:{state}={strip(icon)}" for state, icon in sorted(rule["state"].items())]
    ranges = sorted(rule["range"].items(), key=lambda kv: float(kv[0]))
    parts += [f"r:{threshold}={strip(icon)}" for threshold, icon in ranges]
    return " ".join(parts)


def write_tables(tables: dict, fallbacks: dict[str, str], default: str) -> None:
    rules = [
        rule_line(domain, device_class, rule)
        for domain in sorted(tables)
        for device_class, rule in sorted(tables[domain].items(), key=lambda kv: (kv[0] != "_", kv[0]))
    ]
    out = [
        KT_HEADER.format(
            source=(
                f"Sources: Home Assistant core {HA_CORE_TAG} (homeassistant/components/*/icons.json) and\n"
                f"// frontend {HA_FRONTEND_TAG} (src/data/icons.ts)."
            )
        ),
        "package ee.schimke.ha.rc.icons",
        "",
        "/**",
        " * Home Assistant's default entity icons, as MDI names without the `mdi:` prefix.",
        " *",
        " * [RULES] is core's `entity_component` icon table, one line per domain and device class (`_` is the",
        " * domain's own default): `<domain> <device_class> <default>` followed by `s:<state>=<icon>` state",
        " * variants and `r:<threshold>=<icon>` numeric range variants. [DOMAIN_FALLBACKS] is the frontend's",
        " * `FALLBACK_DOMAIN_ICONS`, used for a domain without a rule, and [DEFAULT_ICON] its",
        " * `DEFAULT_DOMAIN_ICON` for any other domain.",
        " */",
        "internal object HaIconTables {",
        "  val RULES: List<String> =",
        "    listOf(",
        list_items(rules, 6),
        "    )",
        "",
        "  val DOMAIN_FALLBACKS: List<String> =",
        "    listOf(",
        list_items([f"{domain} {icon}" for domain, icon in sorted(fallbacks.items())], 6),
        "    )",
        "",
        f"  const val DEFAULT_ICON = {kt_string(default)}",
        "}",
        "",
    ]
    TABLES_OUT.write_text("\n".join(out))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--cache-dir", type=Path, help="cache downloads here between runs")
    args = parser.parse_args()

    paths = load_mdi(args.cache_dir)
    names_by_camel = {camel(name): name for name in paths}
    tables = load_core_tables(args.cache_dir)
    fallback_ids, default_id = load_frontend_fallbacks(args.cache_dir)
    fallbacks = {domain: uncamel(ident, names_by_camel) for domain, ident in fallback_ids.items()}
    # `homeassistant` / `demo` use the frontend's own HA logo path, not an MDI export.
    fallbacks = {d: n for d, n in fallbacks.items() if n in paths}
    default = uncamel(default_id, names_by_camel)

    wanted: dict[str, str] = {}

    def want(name: str, why: str) -> None:
        if name not in paths:
            sys.exit(f"mdi:{name} ({why}) is not in Material Design Icons {MDI_VERSION}")
        wanted.setdefault(name, why)

    for domain, rules in tables.items():
        for rule in rules.values():
            for icon in [rule["default"], *rule["state"].values(), *rule["range"].values()]:
                want(strip(icon), f"HA core {domain} icons.json")
    for name in [*fallbacks.values(), default]:
        want(name, "HA frontend domain fallback")
    for name in STATE_ICON_SPECIALS:
        want(name, "HA frontend state icon")

    write_tables(tables, fallbacks, default)
    print(
        f"{len(wanted)} distinct icons, "
        f"{sum(len(r) for r in tables.values())} HA icon rules over {len(tables)} domains, "
        f"{len(fallbacks)} domain fallbacks"
    )


if __name__ == "__main__":
    main()
