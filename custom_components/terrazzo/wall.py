"""The wall display API: dashboards as a primitive grid, each card's `.rc` and named values, and
taps, for devices that should not parse Lovelace or Home Assistant's state objects (ESPHome panels,
e-paper frames, kiosks). Design: `docs/architecture/wall-display-api.md`; the rules are in
`wall_api.py`.

Every endpoint is a plain Home Assistant API view: `Authorization: Bearer <access token>`, a
long-lived one for a device, and the device sees what that user may see. A card's design and
values come from the card design add-on's `POST /api/cards/resolve` (design_server.py finds it), or
from a design server at TERRAZZO_DESIGN_SERVER_URL where there is no Supervisor; each call carries
the device's own token, which the add-on checks with Core.
"""
import asyncio
import logging
import os
import time

import voluptuous as vol
from aiohttp import ClientError, ClientTimeout, web
from homeassistant.components.http import HomeAssistantView
from homeassistant.const import EVENT_STATE_CHANGED
from homeassistant.core import Context, callback
from homeassistant.exceptions import HomeAssistantError, ServiceNotFound, Unauthorized
from homeassistant.helpers.aiohttp_client import async_get_clientsession

from . import design_server, edits, wall_api
from .const import CONF_DASHBOARD, DOMAIN
from .design_route import ADDON_PORT

_LOGGER = logging.getLogger(__name__)

RESOLVE_TIMEOUT = ClientTimeout(total=30)
# A burst of state changes (a scene) is resolved once: a woken poll waits this long first.
SETTLE = 0.15
# Resolves in flight per poll.
PARALLEL = 4
# A hub nobody polled for this long is dropped.
IDLE = 600
# Blobs are content-addressed and small; keep the most recent in memory.
BLOB_CACHE = 256
ENV_DESIGN_SERVER = "TERRAZZO_DESIGN_SERVER_URL"
LOVELACE_UPDATED = "lovelace_updated"


def _json(data, status=200):
    response = web.json_response(data, status=status)
    response.headers["Cache-Control"] = "no-store"
    return response


def _error(failure):
    return _json({"message": failure.message}, status=failure.status)


def _look(request):
    """The card style, light or dark, and palette a request asks for."""
    query = request.query
    return (
        query.get("style") or "classic",
        query.get("dark", "").lower() in ("1", "true", "yes"),
        query.get("palette") or None,
    )


async def _dashboard(hass, user, url_path):
    """(url_path or None, the dashboard's config). Raises WallError."""
    key = None if url_path in (None, "", wall_api.DEFAULT_DASHBOARD) else url_path
    found = edits.visible_dashboards(hass, user).get(key)
    if found is None:
        raise wall_api.WallError(404, f"No dashboard {url_path}")
    try:
        config = await found[0].async_load(False)
    except HomeAssistantError:
        raise wall_api.WallError(
            422,
            f"Dashboard {url_path} is generated by Home Assistant and has no saved cards; take "
            "control of it (Edit dashboard → ⋮ → Take control) to show it on a wall display.",
        ) from None
    return key, config


async def _design_server_url(hass):
    if url := os.environ.get(ENV_DESIGN_SERVER):
        return url.rstrip("/")
    info = await design_server.async_find(hass)
    if info is None or info.get("state") != "started" or not info.get("hostname"):
        return None
    return f"http://{info['hostname']}:{ADDON_PORT}"


async def _resolve(hass, base, authorization, card, look):
    """The design add-on's resolve of [card] with its entities' current states: (sha, exact,
    values). Raises WallError."""
    style, dark, palette = look
    states = {}
    for entity in wall_api.entity_ids(card):
        if (state := hass.states.get(entity)) is not None:
            states[entity] = {"state": state.state, "attributes": dict(state.attributes)}
    body = {"card": card, "states": states, "cardStyle": style, "dark": dark}
    if palette:
        body["palette"] = palette
    try:
        async with async_get_clientsession(hass).post(
            f"{base}/api/cards/resolve",
            json=body,
            headers={"Authorization": authorization} if authorization else {},
            timeout=RESOLVE_TIMEOUT,
        ) as response:
            if response.status == 404:
                raise wall_api.WallError(404, f"No design draws a {card.get('type')} card yet.")
            if response.status >= 400:
                raise wall_api.WallError(502, f"The design server answered {response.status}.")
            match = await response.json(content_type=None)
    except (ClientError, TimeoutError, ValueError) as failure:
        raise wall_api.WallError(502, f"The design server didn't answer: {failure}") from None
    sha = match.get("sha256")
    if not isinstance(sha, str) or not wall_api.SHA256.match(sha):
        raise wall_api.WallError(502, "The design server's answer has no design.")
    return sha, bool(match.get("exact")), dict(match.get("bindings") or {})


class Hub:
    """One dashboard in one look: its cards, the entities they show, and a ValueStore."""

    def __init__(self, url_path, look, config):
        self.url_path = url_path
        self.look = look
        self.etag = wall_api.config_etag(config)
        self.layout = wall_api.layout(config, url_path)
        self.cards = {
            cid: wall_api.find_card(config, cid) for cid in wall_api.view_card_ids(self.layout)
        }
        self.by_entity = {}
        for cid, card in self.cards.items():
            for entity in wall_api.entity_ids(card):
                self.by_entity.setdefault(entity, set()).add(cid)
        self.store = wall_api.ValueStore(epoch=int(time.time() * 1000))
        self.dirty = set(self.cards)
        self.wake = asyncio.Event()
        self.used = time.monotonic()

    def entity_changed(self, entity):
        if cids := self.by_entity.get(entity):
            self.dirty |= cids
            self.wake.set()

    async def refresh(self, hass, base, authorization, card_ids):
        """Resolve the dirty cards among [card_ids]."""
        todo = [cid for cid in card_ids if cid in self.dirty]
        if not todo:
            return
        self.dirty -= set(todo)
        gate = asyncio.Semaphore(PARALLEL)

        async def one(cid):
            async with gate:
                try:
                    sha, exact, values = await _resolve(
                        hass, base, authorization, self.cards[cid], self.look
                    )
                except wall_api.WallError as failure:
                    self.store.fail(cid, failure.message)
                    if failure.status == 502:
                        self.dirty.add(cid)  # Try again on the next poll.
                    return
                self.store.update(cid, sha, wall_api.blob_url(sha), exact, values)

        await asyncio.gather(*(one(cid) for cid in todo))


class Wall:
    """The hubs, and the listeners that keep them current."""

    def __init__(self, hass):
        self.hass = hass
        self.hubs = {}
        self.blobs = {}
        hass.bus.async_listen(EVENT_STATE_CHANGED, self._state_changed)
        hass.bus.async_listen(LOVELACE_UPDATED, self._lovelace_updated)

    @callback
    def _state_changed(self, event):
        entity = event.data.get("entity_id")
        for hub in self.hubs.values():
            hub.entity_changed(entity)

    @callback
    def _lovelace_updated(self, event):
        url_path = event.data.get("url_path") or None
        for key, hub in list(self.hubs.items()):
            if hub.url_path == url_path:
                del self.hubs[key]
                hub.wake.set()  # Its polls answer `reset`.

    def hub(self, url_path, look, config):
        now = time.monotonic()
        for key in [k for k, h in self.hubs.items() if now - h.used > IDLE]:
            del self.hubs[key]
        key = (url_path, look)
        hub = self.hubs.get(key)
        if hub is None or hub.etag != wall_api.config_etag(config):
            if hub is not None:
                hub.wake.set()
            hub = self.hubs[key] = Hub(url_path, look, config)
        hub.used = now
        return hub


def _wall(hass):
    state = hass.data.setdefault(DOMAIN, {})
    if "wall" not in state:
        state["wall"] = Wall(hass)
    return state["wall"]


def _chosen_dashboard(hass):
    entries = hass.config_entries.async_entries(DOMAIN)
    return entries[0].options.get(CONF_DASHBOARD, "") if entries else ""


class WallDashboardsView(HomeAssistantView):
    """`GET /dashboards`: the dashboards this user may see, the chosen wall one first."""

    url = wall_api.API + "/dashboards"
    name = "api:terrazzo:wall:dashboards"

    def __init__(self, hass):
        self.hass = hass

    async def get(self, request):
        user = request["hass_user"]
        visible = edits.visible_dashboards(self.hass, user)
        configs = {key: config for key, (_, config) in visible.items()}
        return _json(
            {"dashboards": wall_api.dashboard_list(configs, _chosen_dashboard(self.hass))}
        )


class WallLayoutView(HomeAssistantView):
    """`GET /dashboards/{url_path}`: one dashboard as a primitive grid. `ETag` is the config's."""

    url = wall_api.API + "/dashboards/{url_path}"
    name = "api:terrazzo:wall:layout"

    def __init__(self, hass):
        self.hass = hass

    async def get(self, request, url_path):
        try:
            _, config = await _dashboard(self.hass, request["hass_user"], url_path)
            layout = wall_api.layout(config, url_path)
        except wall_api.WallError as failure:
            return _error(failure)
        etag = f'"{layout["etag"]}"'
        if request.headers.get("If-None-Match") == etag:
            return web.Response(status=304, headers={"ETag": etag})
        response = _json(layout)
        response.headers["ETag"] = etag
        return response


class WallCardView(HomeAssistantView):
    """`GET /cards/{url_path}/{card_id}`: one card's design, values and tap, resolved now."""

    url = wall_api.API + "/cards/{url_path}/{card_id}"
    name = "api:terrazzo:wall:card"

    def __init__(self, hass):
        self.hass = hass

    async def get(self, request, url_path, card_id):
        try:
            _, config = await _dashboard(self.hass, request["hass_user"], url_path)
            card = wall_api.find_card(config, card_id)
            base = await _design_server_url(self.hass)
            if base is None:
                raise wall_api.WallError(503, "No card design server: install the Terrazzo Card Designs add-on.")
            sha, exact, values = await _resolve(
                self.hass, base, request.headers.get("Authorization"), card, _look(request)
            )
        except wall_api.WallError as failure:
            return _error(failure)
        return _json(
            {
                "id": card_id,
                "type": card.get("type"),
                "entities": wall_api.entity_ids(card),
                "design": sha,
                "rc": wall_api.blob_url(sha),
                "exact": exact,
                "values": values,
                "tap": wall_api.resolve_tap(card),
            }
        )


class WallValuesView(HomeAssistantView):
    """`GET /values/{url_path}?cards=&since=&wait=`: a long poll. Answers at once with what changed
    after cursor `since` (everything, without one), or waits up to `wait` seconds for a change."""

    url = wall_api.API + "/values/{url_path}"
    name = "api:terrazzo:wall:values"

    def __init__(self, hass):
        self.hass = hass

    async def get(self, request, url_path):
        try:
            key, config = await _dashboard(self.hass, request["hass_user"], url_path)
            base = await _design_server_url(self.hass)
            if base is None:
                raise wall_api.WallError(503, "No card design server: install the Terrazzo Card Designs add-on.")
            hub = _wall(self.hass).hub(key, _look(request), config)
        except wall_api.WallError as failure:
            return _error(failure)
        authorization = request.headers.get("Authorization")
        card_ids = wall_api.parse_card_ids(request.query.get("cards", ""), hub.cards)
        cursor = request.query.get("since", "")
        since = hub.store.since(cursor)
        # A cursor from before a restart or a dashboard edit: everything again, and a hint to
        # refetch the layout when `etag` moved.
        reset = bool(cursor) and not hub.store.is_current(cursor)
        wait = wall_api.clamp_wait(request.query.get("wait"))

        await hub.refresh(self.hass, base, authorization, card_ids)
        changes = hub.store.changes(card_ids, since)
        deadline = time.monotonic() + wait
        wanted = set(card_ids)
        while not changes and not reset and (left := deadline - time.monotonic()) > 0:
            hub.wake.clear()
            if hub.dirty & wanted:
                left = 0  # Changed while we resolved: don't wait for the next one.
            if left:
                try:
                    await asyncio.wait_for(hub.wake.wait(), left)
                except TimeoutError:
                    break
            if _wall(self.hass).hubs.get((key, hub.look)) is not hub:
                reset = True  # The dashboard changed: the device fetches its layout again.
                break
            await asyncio.sleep(SETTLE)
            await hub.refresh(self.hass, base, authorization, card_ids)
            changes = hub.store.changes(card_ids, since)
        hub.used = time.monotonic()
        return _json(
            {
                "cursor": hub.store.cursor(),
                "etag": hub.etag,
                "reset": reset,
                "cards": {} if reset and not changes else changes,
            }
        )


class WallBlobView(HomeAssistantView):
    """`GET /blobs/{sha}.rc`: a design's RemoteCompose bytes. Content-addressed, so immutable."""

    url = wall_api.API + "/blobs/{sha}.rc"
    name = "api:terrazzo:wall:blob"

    def __init__(self, hass):
        self.hass = hass

    async def get(self, request, sha):
        if not wall_api.SHA256.match(sha):
            return _json({"message": "Not a design"}, status=404)
        headers = {
            "Cache-Control": "private, max-age=31536000, immutable",
            "ETag": f'"{sha}"',
            "Content-Type": "application/octet-stream",
        }
        if request.headers.get("If-None-Match") == f'"{sha}"':
            return web.Response(status=304, headers=headers)
        wall = _wall(self.hass)
        body = wall.blobs.get(sha)
        if body is None:
            base = await _design_server_url(self.hass)
            if base is None:
                return _json({"message": "No card design server"}, status=503)
            auth = request.headers.get("Authorization")
            try:
                async with async_get_clientsession(self.hass).get(
                    f"{base}/designs/v1/blobs/{sha}.rc",
                    headers={"Authorization": auth} if auth else {},
                    timeout=RESOLVE_TIMEOUT,
                ) as response:
                    if response.status != 200:
                        return _json({"message": "No such design"}, status=404)
                    body = await response.read()
            except (ClientError, TimeoutError):
                return _json({"message": "The design server didn't answer"}, status=502)
            wall.blobs[sha] = body
            while len(wall.blobs) > BLOB_CACHE:
                wall.blobs.pop(next(iter(wall.blobs)))
        return web.Response(body=body, headers=headers)


class WallActionView(HomeAssistantView):
    """`POST /actions/{url_path}/{card_id}` with `{"action": <the ha host action's string>}` (or
    nothing, for the card itself): runs the card's own action as this user."""

    url = wall_api.API + "/actions/{url_path}/{card_id}"
    name = "api:terrazzo:wall:action"

    def __init__(self, hass):
        self.hass = hass

    async def post(self, request, url_path, card_id):
        user = request["hass_user"]
        try:
            _, config = await _dashboard(self.hass, user, url_path)
            card = wall_api.find_card(config, card_id)
        except wall_api.WallError as failure:
            return _error(failure)
        value = None
        if request.body_exists:
            try:
                body = await request.json()
            except ValueError:
                return _json({"message": "Not JSON"}, status=400)
            value = body.get("action") if isinstance(body, dict) else None
        action = wall_api.resolve_tap(card, value)
        call = wall_api.service_call(action)
        if call is None:
            # More-info, navigate and url are the device's: it gets what the card's config says.
            return _json({"ran": None, "action": action})
        domain, service, data = call
        try:
            await self.hass.services.async_call(
                domain, service, data, blocking=True, context=Context(user_id=user.id)
            )
        except Unauthorized:
            return _json({"message": f"Not allowed: {domain}.{service}"}, status=403)
        except ServiceNotFound:
            return _json({"message": f"No service {domain}.{service}"}, status=400)
        except (HomeAssistantError, ValueError, vol.Invalid) as failure:
            return _json({"message": f"{domain}.{service} failed: {failure}"}, status=400)
        return _json({"ran": f"{domain}.{service}", "action": action})


@callback
def async_register(hass):
    for view in (
        WallDashboardsView,
        WallLayoutView,
        WallCardView,
        WallValuesView,
        WallBlobView,
        WallActionView,
    ):
        hass.http.register_view(view(hass))
