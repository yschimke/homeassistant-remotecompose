def _json(data, status=200):
    response = web.json_response(data, status=status)
    response.headers["Cache-Control"] = "no-store"
    return response


def _error(failure):
    return _json({"message": failure.message}, status=failure.status)


def _look(request):
    """The card style, light or dark, palette, and player a request asks for. The player is the
    display a small device draws on and what it can play, `(density, font_scale, width, height,
    profile)` from those query names: the design server makes each design for it (wall_api.player)."""
    query = request.query
    return (
        query.get("style") or "classic",
        query.get("dark", "").lower() in ("1", "true", "yes"),
        query.get("palette") or None,
        wall_api.player(
            query.get("density"),
            query.get("font_scale"),
            query.get("width"),
            query.get("height"),
            query.get("profile"),
        ),
        wall_api.picture_max(query.get("picture_max")),
    )


async def _dashboard(hass, user, url_path):
    """(url_path or None, the dashboard's config). Raises WallError."""
    key = None if url_path in (None, "", wall_api.DEFAULT_DASHBOARD) else url_path
    found = edits.visible_dashboards(hass, user).get(key)
    if found is None:
        raise wall_api.WallError(404, f"No dashboard {url_path}")
    try:
        config = await found[0].async_load(False)
    except HomeAssistantError:
        raise wall_api.WallError(
            422,
            f"Dashboard {url_path} is generated by Home Assistant and has no saved cards; take "
            "control of it (Edit dashboard → ⋮ → Take control) to show it on a wall display.",
        ) from None
    return key, config


async def _design_server_url(hass):
    if url := os.environ.get(ENV_DESIGN_SERVER):
        return url.rstrip("/")
    info = await design_server.async_find(hass)
    if info is None or info.get("state") != "started" or not info.get("hostname"):
        return None
    return f"http://{info['hostname']}:{ADDON_PORT}"


def _state_text(hass, user, entity):
    """[entity]'s state string if [user] may read it, else None."""
    if not user.permissions.check_entity(entity, POLICY_READ):
        return None
    state = hass.states.get(entity)
    return None if state is None else state.state


def _shown(hass, user, card):
    """The card a wall display draws for [card] now (through `conditional` wrappers). Raises
    WallError(404) while its conditions hide it."""
    shown = wall_api.shown_card(card, lambda entity: _state_text(hass, user, entity))
    if shown is None:
        raise wall_api.WallError(404, "This conditional card is hidden by its conditions.")
    return shown


def _readable(hass, user, card):
    """[card]'s entities' states that [user] may read, by entity id."""
    out = {}
    for entity in wall_api.entity_ids(card):
        if user.permissions.check_entity(entity, POLICY_READ) and (
            state := hass.states.get(entity)
        ) is not None:
            out[entity] = state
    return out


def _resolve_states(hass, user, card):
    """[card]'s readable states plus the shared entities' ([wall_api.SHARED_ENTITIES]) the user may
    read: what a resolve sends, so a design's `HA:sun.sun.*` values are this home's sun."""
    out = _readable(hass, user, card)
    for entity in wall_api.SHARED_ENTITIES:
        if entity not in out and user.permissions.check_entity(entity, POLICY_READ):
            if (state := hass.states.get(entity)) is not None:
                out[entity] = state
    return out


def _pictures(hass, user, card):
    """entity id → `entity_picture` for [card]'s entities [user] may read."""
    return {
        entity: state.attributes["entity_picture"]
        for entity, state in _readable(hass, user, card).items()
        if isinstance(state.attributes.get("entity_picture"), str)
    }


async def _resolve(hass, user, base, authorization, card, look):
    """The design add-on's resolve of [card] with the current states of its entities [user] may
    read: (sha, exact, values). An entity they may not read, or that doesn't exist, is sent as
    unavailable, as Home Assistant's own card shows it: the card still has its exact design, with
    that slot's unavailable values. Raises WallError."""
    style, dark, palette, player = look[:4]
    states = {
        entity: {"state": state.state, "attributes": dict(state.attributes)}
        for entity, state in _resolve_states(hass, user, card).items()
    }
    for entity in wall_api.entity_ids(card):
        states.setdefault(entity, {"state": "unavailable", "attributes": {}})
    body = {"card": card, "states": states, "cardStyle": style, "dark": dark}
    # The home's zone, not the add-on's: the sun's times are minutes of the home's local day.
    if time_zone := getattr(hass.config, "time_zone", None):
        body["timeZone"] = time_zone
    if palette:
        body["palette"] = palette
    if player:
        display = {"density": player[0], "fontScale": player[1]}
        if player[2] is not None:
            display.update(width=player[2], height=player[3])
        body["player"] = {"display": display}
        if player[4]:
            body["player"]["profile"] = player[4]
    try:
        async with async_get_clientsession(hass).post(
            f"{base}/api/cards/resolve",
            json=body,
            headers={"Authorization": authorization} if authorization else {},
            timeout=RESOLVE_TIMEOUT,
        ) as response:
            if response.status == 404:
                raise wall_api.WallError(404, f"No design draws this {card.get('type')} card yet.")
            if response.status >= 400:
                raise wall_api.WallError(502, f"The design server answered {response.status}.")
            match = await response.json(content_type=None)
    except (ClientError, TimeoutError, ValueError) as failure:
        raise wall_api.WallError(502, f"The design server didn't answer: {failure}") from None
    sha = match.get("sha256")
    if not isinstance(sha, str) or not wall_api.SHA256.match(sha):
        raise wall_api.WallError(502, "The design server's answer has no design.")
    return sha, bool(match.get("exact")), dict(match.get("bindings") or {})


class Hub:
    """One dashboard in one look for one user: its cards, the entities they show, and a
    ValueStore. Per user, since what a user may read decides the values."""

    def __init__(self, key, user, url_path, look, config):
        self.key = key
        self.user = user
        self.url_path = url_path
        self.look = look
        self.etag = wall_api.config_etag(config)
        self.config = config
        self.layout = wall_api.layout(config, url_path)
        self.cards = {}
        self.by_entity = {}
        self.locks = {}
        self.dirty = set()
        for cid in wall_api.view_card_ids(self.layout):
            self._add(cid)
        # Cards whose last resolve carried a shared value (`HA:sun.sun.*`): a shared entity's change
        # changes them, and only them.
        self.shared_readers = set()
        self.store = wall_api.ValueStore(epoch=int(time.time() * 1000))
        self.retry = set()
        # A player with a screen size polls screens: each view packed a screen at a time
        # (wall_api.screens), view index → its screen ids, in order. A card found not to draw in a
        # stack is set [apart], one with no design at all is [skip]ped, and the views are packed
        # again ([_pack]), so the list can change; the store stamps each version.
        self.screens = {}
        # Card id → whether it draws inside a stack (a one-card stack of it has a design).
        self.stackable = {}
        self.apart = set()
        self.skip = set()
        self.wake = asyncio.Event()
        self._pack()
        self.used = time.monotonic()

    def _add(self, cid):
        """Track card or screen [cid]: its config, the entities that change it, dirty."""
        if cid in self.cards:
            return
        card = wall_api.find_card(self.config, cid)
        self.cards[cid] = card
        for entity in wall_api.watched_entities(card):
            self.by_entity.setdefault(entity, set()).add(cid)
        # One resolve per card at a time, so a later one (with later states) is always stored last.
        self.locks[cid] = asyncio.Lock()
        self.dirty.add(cid)

    def _pack(self):
        """Pack each view into screens for the player's height, with what's known of which cards
        stack. Returns every screen id."""
        player = self.look[3]
        if player is None or player[3] is None:
            return []
        wall_api.screens(self.layout, player[3], self.apart, self.skip, player[2])
        for view in self.layout["views"]:
            self._set_screens(view["index"], [screen["id"] for screen in view["screens"]])
        return [sid for ids in self.screens.values() for sid in ids]

    def _set_screens(self, view, ids):
        for sid in ids:
            self._add(sid)
        self.screens[view] = list(ids)
        self.store.set_screens(view, ids)

    def entity_changed(self, entity):
        cids = set(self.by_entity.get(entity, ()))
        if entity in wall_api.SHARED_ENTITIES:
            cids |= self.shared_readers
        if cids:
            self.dirty |= cids
            self.wake.set()

    async def refresh(self, hass, base, authorization, card_ids):
        """Resolve the dirty cards among [card_ids]."""
        todo = [cid for cid in card_ids if cid in self.dirty]
        if not todo:
            return
        self.dirty -= set(todo)
        gate = asyncio.Semaphore(PARALLEL)

        unstacked = []
        undrawn = []

        async def one(cid):
            async with gate, self.locks[cid]:
                try:
                    # States are read once the lock is held: after any resolve still in flight.
                    # A `conditional` is drawn as the card its conditions show; while they hide it
                    # the answer is `hidden`, and when they hold again the card comes whole.
                    card = wall_api.shown_card(
                        self.cards[cid], lambda entity: _state_text(hass, self.user, entity)
                    )
                    if card is None:
                        if self.store.hide(cid):
                            self.wake.set()
                        return
                    if self.look[3] is not None:
                        card = wall_api.panel_card(card, self.look[3], self.look[4])
                    sha, exact, values = await _resolve(
                        hass, self.user, base, authorization, card, self.look
                    )
                except wall_api.WallError as failure:
                    if failure.status == 404 and wall_api.screen_size(cid) > 1:
                        unstacked.append(cid)  # Packed again once every resolve is done.
                        return
                    if failure.status == 404 and wall_api.screen_size(cid) == 1:
                        # A card with no design: a screen saying so is a page with nothing on it.
                        view, first, _ = wall_api.screen_range(cid)
                        undrawn.extend(c for _, c in wall_api.screen_cards(self.layout, view, first, first))
                        return
                    if self.store.fail(cid, failure.message):
                        self.wake.set()
                    if failure.status == 502:
                        self.retry.add(cid)  # Again on the next poll, not in a loop in this one.
                    return
                if wall_api.reads_shared(values):
                    self.shared_readers.add(cid)
                else:
                    self.shared_readers.discard(cid)
                values.update(
                    wall_api.picture_values(
                        self.url_path, cid, card, _pictures(hass, self.user, card)
                    )
                )
                if self.store.update(cid, sha, wall_api.blob_url(sha), exact, values):
                    # Wakes polls that saw this card dirty but left the resolve to this one.
                    self.wake.set()

        await asyncio.gather(*(one(cid) for cid in todo))
        if unstacked or undrawn:
            self.skip.update(undrawn)
            for sid in unstacked:
                await self._set_apart(hass, base, authorization, sid)
            # Each pass sets more cards apart or skips them, so this ends.
            await self.refresh(hass, base, authorization, self._pack())

    async def _set_apart(self, hass, base, authorization, sid):
        """Screen [sid]'s stack has no design: set apart its cards that don't draw in a stack, or,
        when each does on its own, all of them."""
        view, first, last = wall_api.screen_range(sid)
        left_out = wall_api.screen_left_out(sid)
        members = [cid for _, cid in wall_api.screen_cards(self.layout, view, first, last, left_out)]
        alone = [cid for cid in members if not await self._stacks(hass, base, authorization, cid)]
        self.apart.update(alone or members)

    async def _stacks(self, hass, base, authorization, cid):
        """Whether card [cid] draws inside a stack: a one-card stack of it has a design. A card with
        no entities (a heading, markdown) does, beside one that has them."""
        if cid in self.stackable:
            return self.stackable[cid]
        card = self.cards[cid]
        result = True
        if wall_api.entity_ids(card):
            shown = wall_api.shown_card(card, lambda entity: _state_text(hass, self.user, entity))
            if shown is not None:
                stack = {"type": "vertical-stack", "cards": [wall_api.panel_card(shown, self.look[3], self.look[4])]}
                try:
                    await _resolve(hass, self.user, base, authorization, stack, self.look)
                except wall_api.WallError as failure:
                    if failure.status != 404:
                        return True  # Not known yet: try it in its run.
                    result = False
        self.stackable[cid] = result
        return result


class Wall:
    """The hubs, and the listeners that keep them current."""

    def __init__(self, hass):
        self.hass = hass
        self.hubs = {}
        self.blobs = {}
        self.fonts = {}
        self.font_manifest = (None, 0)
        self.pictures = {}
        hass.bus.async_listen(EVENT_STATE_CHANGED, self._state_changed)
        hass.bus.async_listen(LOVELACE_UPDATED, self._lovelace_updated)

    @callback
    def _state_changed(self, event):
        entity = event.data.get("entity_id")
        for hub in self.hubs.values():
            hub.entity_changed(entity)

    @callback
    def _lovelace_updated(self, event):
        url_path = event.data.get("url_path") or None
        for key, hub in list(self.hubs.items()):
            if hub.url_path == url_path:
                del self.hubs[key]
                hub.wake.set()  # Its polls answer `reset`.

    def hub(self, user, url_path, look, config):
        now = time.monotonic()
        for key in [k for k, h in self.hubs.items() if now - h.used > IDLE]:
            del self.hubs[key]
        key = (url_path, user.id, look)
        hub = self.hubs.get(key)
        if hub is None or hub.etag != wall_api.config_etag(config):
            if hub is not None:
                hub.wake.set()
            hub = self.hubs[key] = Hub(key, user, url_path, look, config)
        hub.used = now
        return hub


def _wall(hass):
    state = hass.data.setdefault(DOMAIN, {})
    if "wall" not in state:
        state["wall"] = Wall(hass)
    return state["wall"]


def _chosen_dashboard(hass):
    entries = hass.config_entries.async_entries(DOMAIN)
    return entries[0].options.get(CONF_DASHBOARD, "") if entries else ""


class WallDashboardsView(HomeAssistantView):
    """`GET /dashboards`: the dashboards this user may see and a wall can show, the chosen wall one
    first. One without saved cards (Overview, generated by Home Assistant until someone takes
    control of it) is left out: every layout request for it would be refused."""

    url = wall_api.API + "/dashboards"
    name = "api:terrazzo:wall:dashboards"

    def __init__(self, hass):
        self.hass = hass

    async def get(self, request):
        user = request["hass_user"]
        configs = {}
        for key, (dashboard, config) in edits.visible_dashboards(self.hass, user).items():
            try:
                cards = await dashboard.async_load(False)
            except HomeAssistantError:
                continue
            if wall_api.has_cards(cards):
                configs[key] = config
        return _json(
            {"dashboards": wall_api.dashboard_list(configs, _chosen_dashboard(self.hass))}
        )


class WallLayoutView(HomeAssistantView):
    """`GET /dashboards/{url_path}`: one dashboard as a primitive grid. `ETag` is the config's."""

    url = wall_api.API + "/dashboards/{url_path}"
    name = "api:terrazzo:wall:layout"

    def __init__(self, hass):
        self.hass = hass

    async def get(self, request, url_path):
        try:
            _, config = await _dashboard(self.hass, request["hass_user"], url_path)
            layout = wall_api.layout(config, url_path)
        except wall_api.WallError as failure:
            return _error(failure)
        etag = f'"{layout["etag"]}"'
        if request.headers.get("If-None-Match") == etag:
            return web.Response(status=304, headers={"ETag": etag})
        response = _json(layout)
        response.headers["ETag"] = etag
        return response


class WallCardView(HomeAssistantView):
    """`GET /cards/{url_path}/{card_id}`: one card's design, values and tap, resolved now."""

    url = wall_api.API + "/cards/{url_path}/{card_id}"
    name = "api:terrazzo:wall:card"

    def __init__(self, hass):
        self.hass = hass

    async def get(self, request, url_path, card_id):
        try:
            _, config = await _dashboard(self.hass, request["hass_user"], url_path)
            card = _shown(self.hass, request["hass_user"], wall_api.find_card(config, card_id))
            base = await _design_server_url(self.hass)
            if base is None:
                raise wall_api.WallError(503, "No card design server: install the Terrazzo Card Designs add-on.")
            look = _look(request)
            sha, exact, values = await _resolve(
                self.hass,
                request["hass_user"],
                base,
                request.headers.get("Authorization"),
                wall_api.panel_card(card, look[3], look[4]) if look[3] is not None else card,
                look,
            )
        except wall_api.WallError as failure:
            return _error(failure)
        values.update(
            wall_api.picture_values(
                url_path, card_id, card, _pictures(self.hass, request["hass_user"], card)
            )
        )
        return _json(
            {
                "id": card_id,
                "type": card.get("type"),
                "entities": wall_api.entity_ids(card),
                "design": sha,
                "rc": wall_api.blob_url(sha),
                "exact": exact,
                "values": values,
                "tap": wall_api.resolve_tap(card),
            }
        )


class WallValuesView(HomeAssistantView):
    """`GET /values/{url_path}?cards=&since=&wait=`: a long poll. Answers at once with what changed
    after cursor `since` (everything, without one), or waits up to `wait` seconds for a change."""

    url = wall_api.API + "/values/{url_path}"
    name = "api:terrazzo:wall:values"

    def __init__(self, hass):
        self.hass = hass

    async def get(self, request, url_path):
        try:
            key, config = await _dashboard(self.hass, request["hass_user"], url_path)
            base = await _design_server_url(self.hass)
            if base is None:
                raise wall_api.WallError(503, "No card design server: install the Terrazzo Card Designs add-on.")
            hub = _wall(self.hass).hub(request["hass_user"], key, _look(request), config)
        except wall_api.WallError as failure:
            return _error(failure)
        authorization = request.headers.get("Authorization")
        # `screens=<view>`: that view's screens (a player with a screen size), whose list can change
        # as screens without a design are split; else the cards asked for.
        screens_of = request.query.get("screens")
        view = int(screens_of) if screens_of and screens_of.isdigit() else None

        def wanted_ids():
            if view is not None:
                return list(hub.screens.get(view, []))
            return wall_api.parse_card_ids(request.query.get("cards", ""), hub.cards)

        cursor = request.query.get("since", "")
        since = hub.store.since(cursor)
        # A cursor from before a restart or a dashboard edit: everything again, and a hint to
        # refetch the layout when `etag` moved.
        reset = bool(cursor) and not hub.store.is_current(cursor)
        wait = wall_api.clamp_wait(request.query.get("wait"))

        hub.dirty |= hub.retry
        hub.retry.clear()
        await hub.refresh(self.hass, base, authorization, wanted_ids())
        card_ids = wanted_ids()
        changes = hub.store.changes(card_ids, since)
        deadline = time.monotonic() + wait
        while not changes and not reset and (left := deadline - time.monotonic()) > 0:
            hub.wake.clear()
            if hub.dirty & set(card_ids):
                left = 0  # Changed while we resolved: don't wait for the next one.
            if left:
                try:
                    await asyncio.wait_for(hub.wake.wait(), left)
                except TimeoutError:
                    break
            if _wall(self.hass).hubs.get(hub.key) is not hub:
                reset = True  # The dashboard changed: the device fetches its layout again.
                break
            await asyncio.sleep(SETTLE)
            await hub.refresh(self.hass, base, authorization, wanted_ids())
            card_ids = wanted_ids()
            changes = hub.store.changes(card_ids, since)
        hub.used = time.monotonic()
        # Read with the cursor, with no await between: whatever another poll's resolve stored while
        # this one waited is in this answer, never behind the cursor it returns.
        card_ids = wanted_ids()
        changes = hub.store.changes(card_ids, since)
        answer = {
            "cursor": hub.store.cursor(),
            "etag": hub.etag,
            "reset": reset,
            "cards": {} if reset and not changes else changes,
        }
        if view is not None:
            screens = hub.store.screens_since(view, 0 if reset else since)
            if screens is not None:
                answer["screens"] = screens
        return _json(answer)


class WallBlobView(HomeAssistantView):
    """`GET /blobs/{sha}.rc`: a design's RemoteCompose bytes. Content-addressed, so immutable."""

    url = wall_api.API + "/blobs/{sha}.rc"
    name = "api:terrazzo:wall:blob"

    def __init__(self, hass):
        self.hass = hass

    async def get(self, request, sha):
        if not wall_api.SHA256.match(sha):
            return _json({"message": "Not a design"}, status=404)
        headers = {
            "Cache-Control": "private, max-age=31536000, immutable",
            "ETag": f'"{sha}"',
            "Content-Type": "application/octet-stream",
        }
        if request.headers.get("If-None-Match") == f'"{sha}"':
            return web.Response(status=304, headers=headers)
        wall = _wall(self.hass)
        body = wall.blobs.get(sha)
        if body is None:
            base = await _design_server_url(self.hass)
            if base is None:
                return _json({"message": "No card design server"}, status=503)
            auth = request.headers.get("Authorization")
            try:
                async with async_get_clientsession(self.hass).get(
                    f"{base}/designs/v1/blobs/{sha}.rc",
                    headers={"Authorization": auth} if auth else {},
                    timeout=RESOLVE_TIMEOUT,
                ) as response:
                    if response.status != 200:
                        return _json({"message": "No such design"}, status=404)
                    body = await response.read()
            except (ClientError, TimeoutError):
                return _json({"message": "The design server didn't answer"}, status=502)
            wall.blobs[sha] = body
            while len(wall.blobs) > BLOB_CACHE:
                wall.blobs.pop(next(iter(wall.blobs)))
        return web.Response(body=body, headers=headers)


class WallActionView(HomeAssistantView):
    """`POST /actions/{url_path}/{card_id}` with `{"action": <the ha host action's string>}` (or
    nothing, for the card itself): runs the card's own action as this user."""

    url = wall_api.API + "/actions/{url_path}/{card_id}"
    name = "api:terrazzo:wall:action"

    def __init__(self, hass):
        self.hass = hass

    async def post(self, request, url_path, card_id):
        user = request["hass_user"]
        try:
            _, config = await _dashboard(self.hass, user, url_path)
            card = _shown(self.hass, user, wall_api.find_card(config, card_id))
        except wall_api.WallError as failure:
            return _error(failure)
        value = None
        if request.body_exists:
            try:
                body = await request.json()
            except ValueError:
                return _json({"message": "Not JSON"}, status=400)
            value = body.get("action") if isinstance(body, dict) else None
        action = wall_api.resolve_tap(card, value)
        call = wall_api.service_call(action)
        if call is None:
            # More-info, navigate and url are the device's: it gets what the card's config says.
            return _json({"ran": None, "action": action})
        domain, service, data = call
        try:
            await self.hass.services.async_call(
                domain, service, data, blocking=True, context=Context(user_id=user.id)
            )
        except Unauthorized:
            return _json({"message": f"Not allowed: {domain}.{service}"}, status=403)
        except ServiceNotFound:
            return _json({"message": f"No service {domain}.{service}"}, status=400)
        except (HomeAssistantError, ValueError, vol.Invalid) as failure:
            return _json({"message": f"{domain}.{service} failed: {failure}"}, status=400)
        return _json({"ran": f"{domain}.{service}", "action": action})


