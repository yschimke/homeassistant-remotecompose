// `BundledDemoDashboards` for Wasm: each demo dashboard file under src/androidMain/resources, as a
// string constant by its classpath path. Android and the JVM read the files themselves.
val bundledDemoDashboards by tasks.registering {
  val dashboards = layout.projectDirectory.dir("src/androidMain/resources/dashboards")
  val out = layout.buildDirectory.dir("generated/bundledDemoDashboards")
  inputs
    .dir(dashboards)
    .withPathSensitivity(PathSensitivity.RELATIVE)
    .withPropertyName("dashboards")
  outputs.dir(out).withPropertyName("source")
  doLast {
    fun literal(text: String): String = buildString {
      append('"')
      for (c in text) {
        when (c) {
          '\\' -> append("\\\\")
          '"' -> append("\\\"")
          '$' -> append("\\$")
          '\n' -> append("\\n")
          '\r' -> append("\\r")
          '\t' -> append("\\t")
          else -> append(c)
        }
      }
      append('"')
    }
    val root = dashboards.asFile
    val files =
      root.walkTopDown().filter { it.isFile && it.name.endsWith(".json") }.sortedBy { it.path }
    out.get().asFile.deleteRecursively()
    val dir = out.get().asFile.resolve("ee/schimke/terrazzo/core/session")
    dir.mkdirs()
    dir
      .resolve("BundledDemoDashboards.kt")
      .writeText(
        buildString {
          appendLine("// Generated by :terrazzo-core:bundledDemoDashboards. Do not edit.")
          appendLine("package ee.schimke.terrazzo.core.session")
          appendLine()
          appendLine("internal object BundledDemoDashboards {")
          appendLine("  /** The demo dashboard file at [path] (`/dashboards/<slug>/<file>`). */")
          appendLine("  fun file(path: String): String? =")
          appendLine("    when (path) {")
          for (file in files) {
            val path = "/dashboards/" + file.relativeTo(root).invariantSeparatorsPath
            // Chunked: one literal per 16k characters keeps every constant small.
            val chunks = file.readText().chunked(16_384).joinToString(", ") { literal(it) }
            appendLine("      ${literal(path)} -> listOf($chunks).joinToString(\"\")")
          }
          appendLine("      else -> null")
          appendLine("    }")
          appendLine("}")
        },
      )
  }
}

